const catalogs: Record<UiLocale, Record<MessageKey, string>> = { zh_CN: zhCN, en };

export function resolveUiLocale(value?: string): UiLocale {
  const language = value ?? chrome.i18n.getUILanguage();
  return language.toLowerCase().startsWith("zh") ? "zh_CN" : "en";
}

export function createTranslator(
  locale: UiLocale,
): (key: MessageKey, ...values: string[]) => string {
  return (key, ...values) =>
    values.reduce(
      (message, value, index) => message.replaceAll(`{${index}}`, value),
      catalogs[locale][key],
    );
}
